"""Generate readable Markdown from the authoritative RFCXML source."""
import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
XML = ROOT / 'draft/draft-acosta-crypto-agility-manifest-02.xml'
MARKDOWN = XML.with_suffix('.md')


def inline(element):
    text = element.text or ''
    for child in element:
        text += '[' + child.attrib['target'] + ']' if child.tag == 'xref' else inline(child)
        text += child.tail or ''
    return text.strip()


def render(path=XML):
    root = ET.parse(path).getroot()
    lines = ['# ' + root.findtext('front/title'), '',
             '`' + root.attrib['docName'] + '` | individual Informational proposal | [publication status](https://datatracker.ietf.org/doc/draft-acosta-crypto-agility-manifest/)', '',
             'Author: Leon Acosta, QuantaKrypto, leon@quantakrypto.com', '',
             '<!-- Generated by python -m tools.render_draft; edit RFCXML. -->', '',
             '## Abstract', '', root.findtext('front/abstract/t'), '']
    for section in list(root.findall('middle/section')) + list(root.findall('back/section')):
        lines += ['## ' + section.findtext('name'), '']
        for element in section:
            if element.tag == 't':
                lines += [inline(element), '']
            elif element.tag == 'sourcecode':
                lines += ['```' + element.attrib.get('type', ''), element.text or '', '```', '']
    for references in root.findall('back/references'):
        lines += ['## ' + references.findtext('name'), '']
        for ref in references.findall('reference'):
            lines += ['- [' + ref.attrib['anchor'] + '] [' + ref.findtext('front/title') + '](' + ref.attrib['target'] + ')']
        lines += ['']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        return 0 if MARKDOWN.read_text() == expected else 1
    MARKDOWN.write_text(expected)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
